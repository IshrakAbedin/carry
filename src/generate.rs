//! Generator: `Manifest` → `conanfile.txt` / `CMakeLists.txt` render + write-if-changed.
//!
//! DESIGN.md §5 is the spec for the rendered content. Both files are
//! regenerated on every `build`/`run`/`test` (D3): rendered in memory and
//! written only when the on-disk content differs, so no state file is needed.

use std::fs;
use std::io;
use std::path::Path;

use anyhow::{Context, Result};

use crate::manifest::Manifest;

/// Render `conanfile.txt` (DESIGN.md §5).
///
/// `[requires]` holds one `conan_ref` line per dependency, sorted by package
/// name (`dependencies` is a `BTreeMap`, so iteration order is sorted). With
/// zero dependencies the `[requires]` section is omitted entirely — Conan
/// tolerates it either way; the empty file stays minimal (T003).
pub fn render_conanfile(m: &Manifest) -> String {
    let mut out = String::new();
    if !m.dependencies.is_empty() {
        out.push_str("[requires]\n");
        for (pkg, version) in &m.dependencies {
            out.push_str(&crate::manifest::conan_ref(pkg, version));
            out.push('\n');
        }
        out.push('\n');
    }
    out.push_str("[generators]\n");
    out.push_str("CMakeDeps\n");
    out.push_str("CMakeToolchain\n");
    out
}

/// Render `CMakeLists.txt` (DESIGN.md §5, test-target link list per D9).
///
/// Targets are emitted per `package.type`: the library target only when the
/// type includes `lib`, the executable only when it includes `bin`; the
/// test target always exists (`tests/test_main.cpp` is always scaffolded)
/// and links the library target (if present) plus the dependencies.
/// An empty `target_link_libraries` list is omitted rather than emitted.
pub fn render_cmake(m: &Manifest) -> String {
    let name = &m.package.name;
    let has_lib = matches!(m.package.kind.as_str(), "lib" | "both");
    let has_bin = matches!(m.package.kind.as_str(), "bin" | "both");
    let deps: Vec<&str> = m.dependencies.keys().map(String::as_str).collect();

    let mut out = String::new();
    out.push_str(&format!(
        "# Generated by carry {} from CARRY.toml — do not edit.\n",
        env!("CARGO_PKG_VERSION")
    ));
    out.push_str("cmake_minimum_required(VERSION 3.21)\n");
    out.push_str(&format!(
        "project({name} VERSION {} LANGUAGES C CXX)\n\n",
        m.package.version
    ));
    out.push_str(&format!("set(CMAKE_C_STANDARD {})\n", std_value(&m.build.c_std)));
    out.push_str(&format!("set(CMAKE_CXX_STANDARD {})\n", std_value(&m.build.cpp_std)));
    out.push_str("set(CMAKE_CXX_STANDARD_REQUIRED ON)\n");
    out.push_str("set(CMAKE_RUNTIME_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/bin)\n");

    if !deps.is_empty() {
        out.push('\n');
        for pkg in &deps {
            out.push_str(&format!("find_package({pkg} REQUIRED)\n"));
        }
    }

    if has_lib {
        out.push('\n');
        out.push_str(&format!("add_library({name}_lib STATIC src/lib.cpp)\n"));
        out.push_str(&format!("target_include_directories({name}_lib PUBLIC include)\n"));
        // The library links the project's dependencies PUBLIC (D10): without
        // this, `#include <fmt/format.h>` in src/lib.cpp resolves to the
        // system's copy (if one exists) and the link fails on mismatched
        // inline-namespace symbols.
        if !deps.is_empty() {
            let dep_targets: Vec<String> =
                deps.iter().map(|pkg| format!("{pkg}::{pkg}")).collect();
            out.push_str(&format!(
                "target_link_libraries({name}_lib PUBLIC {})\n",
                dep_targets.join(" ")
            ));
        }
    }

    if has_bin {
        out.push('\n');
        out.push_str(&format!("add_executable({name} src/main.cpp)\n"));
        let links = link_list(name, has_lib, &deps);
        if !links.is_empty() {
            out.push_str(&format!("target_link_libraries({name} PRIVATE {links})\n"));
        }
        out.push_str(&format!("target_include_directories({name} PRIVATE include)\n"));
    }

    out.push('\n');
    out.push_str("enable_testing()\n");
    out.push_str(&format!("add_executable(test_{name} tests/test_main.cpp)\n"));
    // The test binary links the library target (if present) plus the
    // dependencies. It never links the executable: CMake forbids linking an
    // EXECUTABLE target into another target, and its `main` would clash with
    // the test's own `main` (D9).
    let mut test_links: Vec<String> = Vec::new();
    if has_lib {
        test_links.push(format!("{name}_lib"));
    }
    for pkg in &deps {
        test_links.push(format!("{pkg}::{pkg}"));
    }
    if !test_links.is_empty() {
        out.push_str(&format!(
            "target_link_libraries(test_{name} PRIVATE {})\n",
            test_links.join(" ")
        ));
    }
    out.push_str(&format!("add_test(NAME {name}_tests COMMAND test_{name})\n"));
    out
}

/// Render both generated files for the project at `root` and write each one
/// only if its on-disk content differs. Returns
/// `(conanfile_changed, cmake_changed)`.
pub fn regenerate(m: &Manifest, root: &Path) -> Result<(bool, bool)> {
    let conanfile_changed = write_if_changed(&root.join("conanfile.txt"), &render_conanfile(m))?;
    let cmake_changed = write_if_changed(&root.join("CMakeLists.txt"), &render_cmake(m))?;
    Ok((conanfile_changed, cmake_changed))
}

/// Write `content` to `path` iff it differs from what is already on disk.
/// Returns whether the file was written.
fn write_if_changed(path: &Path, content: &str) -> Result<bool> {
    match fs::read_to_string(path) {
        Ok(existing) if existing == content => return Ok(false),
        Ok(_) => {}
        Err(err) if err.kind() == io::ErrorKind::NotFound => {}
        Err(err) => return Err(err).with_context(|| format!("reading {}", path.display())),
    }
    fs::write(path, content).with_context(|| format!("writing {}", path.display()))?;
    Ok(true)
}

/// `c++23` → `23`, `c11` → `11`: `CMAKE_*_STANDARD` values are bare numbers.
fn std_value(standard: &str) -> &str {
    standard
        .strip_prefix("c++")
        .or_else(|| standard.strip_prefix('c'))
        .unwrap_or(standard)
}

/// Link list for the executable target: the library target first (if
/// present), then one `<pkg>::<pkg>` per dependency (DESIGN.md §3).
fn link_list(name: &str, has_lib: bool, deps: &[&str]) -> String {
    let mut items: Vec<String> = Vec::new();
    if has_lib {
        items.push(format!("{name}_lib"));
    }
    for pkg in deps {
        items.push(format!("{pkg}::{pkg}"));
    }
    items.join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::manifest::{Build, Package};
    use std::collections::BTreeMap;

    fn manifest(kind: &str, deps: &[(&str, &str)]) -> Manifest {
        Manifest {
            package: Package {
                name: "demo".to_string(),
                version: "0.1.0".to_string(),
                kind: kind.to_string(),
            },
            build: Build::default(),
            dependencies: deps
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect::<BTreeMap<String, String>>(),
        }
    }

    const GOLDEN_CONANFILE_NO_DEPS: &str = "\
[generators]
CMakeDeps
CMakeToolchain
";

    const GOLDEN_CMAKE_BIN_NO_DEPS: &str = "# Generated by carry 0.1.0 from CARRY.toml — do not edit.
cmake_minimum_required(VERSION 3.21)
project(demo VERSION 0.1.0 LANGUAGES C CXX)

set(CMAKE_C_STANDARD 11)
set(CMAKE_CXX_STANDARD 23)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_RUNTIME_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/bin)

add_executable(demo src/main.cpp)
target_include_directories(demo PRIVATE include)

enable_testing()
add_executable(test_demo tests/test_main.cpp)
add_test(NAME demo_tests COMMAND test_demo)
";

    const GOLDEN_CMAKE_BIN_WITH_DEP: &str = "# Generated by carry 0.1.0 from CARRY.toml — do not edit.
cmake_minimum_required(VERSION 3.21)
project(demo VERSION 0.1.0 LANGUAGES C CXX)

set(CMAKE_C_STANDARD 11)
set(CMAKE_CXX_STANDARD 23)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_RUNTIME_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/bin)

find_package(fmt REQUIRED)

add_executable(demo src/main.cpp)
target_link_libraries(demo PRIVATE fmt::fmt)
target_include_directories(demo PRIVATE include)

enable_testing()
add_executable(test_demo tests/test_main.cpp)
target_link_libraries(test_demo PRIVATE fmt::fmt)
add_test(NAME demo_tests COMMAND test_demo)
";

    const GOLDEN_CONANFILE_DEPS: &str = "\
[requires]
fmt/10.2.1
zlib/[>=1.3]

[generators]
CMakeDeps
CMakeToolchain
";

    const GOLDEN_CMAKE_BOTH_DEPS: &str = "# Generated by carry 0.1.0 from CARRY.toml — do not edit.
cmake_minimum_required(VERSION 3.21)
project(demo VERSION 0.1.0 LANGUAGES C CXX)

set(CMAKE_C_STANDARD 11)
set(CMAKE_CXX_STANDARD 23)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_RUNTIME_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/bin)

find_package(fmt REQUIRED)
find_package(zlib REQUIRED)

add_library(demo_lib STATIC src/lib.cpp)
target_include_directories(demo_lib PUBLIC include)
target_link_libraries(demo_lib PUBLIC fmt::fmt zlib::zlib)

add_executable(demo src/main.cpp)
target_link_libraries(demo PRIVATE demo_lib fmt::fmt zlib::zlib)
target_include_directories(demo PRIVATE include)

enable_testing()
add_executable(test_demo tests/test_main.cpp)
target_link_libraries(test_demo PRIVATE demo_lib fmt::fmt zlib::zlib)
add_test(NAME demo_tests COMMAND test_demo)
";

    const GOLDEN_CMAKE_LIB_DEP: &str = "# Generated by carry 0.1.0 from CARRY.toml — do not edit.
cmake_minimum_required(VERSION 3.21)
project(demo VERSION 0.1.0 LANGUAGES C CXX)

set(CMAKE_C_STANDARD 11)
set(CMAKE_CXX_STANDARD 23)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_RUNTIME_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/bin)

find_package(fmt REQUIRED)

add_library(demo_lib STATIC src/lib.cpp)
target_include_directories(demo_lib PUBLIC include)
target_link_libraries(demo_lib PUBLIC fmt::fmt)

enable_testing()
add_executable(test_demo tests/test_main.cpp)
target_link_libraries(test_demo PRIVATE demo_lib fmt::fmt)
add_test(NAME demo_tests COMMAND test_demo)
";

    #[test]
    fn golden_bin_no_deps() {
        let m = manifest("bin", &[]);
        assert_eq!(render_conanfile(&m), GOLDEN_CONANFILE_NO_DEPS);
        assert_eq!(render_cmake(&m), GOLDEN_CMAKE_BIN_NO_DEPS);
    }

    #[test]
    fn golden_bin_with_dep() {
        let m = manifest("bin", &[("fmt", "10.2.1")]);
        assert_eq!(render_cmake(&m), GOLDEN_CMAKE_BIN_WITH_DEP);
    }

    #[test]
    fn golden_both_two_deps_sorted() {
        // Inserted out of order; BTreeMap must emit them sorted by name.
        let m = manifest("both", &[("zlib", ">=1.3"), ("fmt", "10.2.1")]);
        assert_eq!(render_conanfile(&m), GOLDEN_CONANFILE_DEPS);
        assert_eq!(render_cmake(&m), GOLDEN_CMAKE_BOTH_DEPS);
    }

    #[test]
    fn golden_lib_only_with_dep() {
        let m = manifest("lib", &[("fmt", "10.2.1")]);
        assert_eq!(render_cmake(&m), GOLDEN_CMAKE_LIB_DEP);
    }

    #[test]
    fn regenerate_writes_then_idempotent() {
        let dir = tempfile::tempdir().unwrap();
        let m = manifest("bin", &[("fmt", "10.2.1")]);

        let (c1, k1) = regenerate(&m, dir.path()).unwrap();
        assert!(c1 && k1, "first run must write both files");

        let conanfile = dir.path().join("conanfile.txt");
        let cmake = dir.path().join("CMakeLists.txt");
        let (c_mtime, k_mtime) = (
            fs::metadata(&conanfile).unwrap().modified().unwrap(),
            fs::metadata(&cmake).unwrap().modified().unwrap(),
        );

        let (c2, k2) = regenerate(&m, dir.path()).unwrap();
        assert!(!c2 && !k2, "second run must change nothing");
        assert_eq!(
            fs::metadata(&conanfile).unwrap().modified().unwrap(),
            c_mtime,
            "conanfile.txt was rewritten on the second run"
        );
        assert_eq!(
            fs::metadata(&cmake).unwrap().modified().unwrap(),
            k_mtime,
            "CMakeLists.txt was rewritten on the second run"
        );
        assert_eq!(fs::read_to_string(&conanfile).unwrap(), render_conanfile(&m));
        assert_eq!(fs::read_to_string(&cmake).unwrap(), render_cmake(&m));
    }

    #[test]
    fn regenerate_rewrites_stale_content() {
        let dir = tempfile::tempdir().unwrap();
        let m = manifest("bin", &[]);
        let conanfile = dir.path().join("conanfile.txt");
        let cmake = dir.path().join("CMakeLists.txt");
        fs::write(&conanfile, "[generators]\n").unwrap();
        fs::write(&cmake, "project(old VERSION 0.0.1)\n").unwrap();

        let (c1, k1) = regenerate(&m, dir.path()).unwrap();
        assert!(c1 && k1, "stale files must be rewritten");
        assert_eq!(fs::read_to_string(&conanfile).unwrap(), render_conanfile(&m));
        assert_eq!(fs::read_to_string(&cmake).unwrap(), render_cmake(&m));
    }
}
